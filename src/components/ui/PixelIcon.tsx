export type PixelIconName = keyof typeof GLYPHS;

/** Merge each glyph row's filled cells into horizontal-run rects (fewer nodes). */
function rectsFor(rows: string[]): { x: number; y: number; w: number }[] {
  const rects: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") w++;
        rects.push({ x, y, w });
        x += w;
      } else {
        x++;
      }
    }
  });
  return rects;
}

const RECTS = Object.fromEntries(
  (Object.keys(GLYPHS) as PixelIconName[]).map((name) => [name, rectsFor(GLYPHS[name])]),
) as Record<PixelIconName, { x: number; y: number; w: number }[]>;

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 14,
  className,
  title,
}: {
  name: PixelIconName;
  /** Rendered square size in px (the art stays crisp at any multiple). */
  size?: number;
  className?: string;
  /** Accessible name; omitted = decorative (aria-hidden). */
  title?: string;
}) {
  return (
    <svg
      viewBox={`0 0 ${GRID} ${GRID}`}
      width={size}
      height={size}
      className={className ? `inline-block align-[-0.12em] ${className}` : "inline-block align-[-0.12em]"}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
    >
      {title ? <title>{title}</title> : null}
      {RECTS[name].map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
});
